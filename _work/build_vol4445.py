# -*- coding: utf-8 -*-
import io, re, sys

BASE = 'genben/vol%d.txt'

def get(v, n):
    for ln in io.open(BASE % v, encoding='utf-8'):
        p = ln.rstrip('\n').split('\t')
        if p[0] == str(n):
            return p[1]
    raise KeyError((v, n))

def seg(v, n, start, end=None, incl_end=True):
    """取段內由 start 起、至 end 標記（含）之逐字片段"""
    s = get(v, n)
    i = s.find(start)
    if i < 0:
        raise ValueError('start not found: %s / %s' % (v, start))
    if end is None:
        return s[i:]
    j = s.find(end, i)
    if j < 0:
        raise ValueError('end not found: %s / %s' % (v, end))
    j = j + len(end) if incl_end else j
    return s[i:j]

def q(v, n, text):
    return '  > 〔卷%d·段%d〕%s' % (v, n, text)

def quote_line(v, n, text):
    assert text in get(v, n), (v, n, text)
    return q(v, n, text)

