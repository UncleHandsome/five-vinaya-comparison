def main():
    for old, new, why in ORIG_FIX:
        n = 0
        for p in RAW:
            d = open(p, encoding='utf-8').read()
            c = d.count(old)
            if c:
                open(p, 'w', encoding='utf-8').write(d.replace(old, new))
                n += c
        print('原文 %s→%s：%d 處（%s）' % (old, new, n, why))

    plain = json.load(open(PLAIN, encoding='utf-8'))
    for src, dst, pre, why in PLAIN_MOVE:
        lines = [l for l in plain.get(src, '').split('\n') if l.strip()]
        hit = [l for l in lines if l.lstrip().startswith(pre)]
        if not hit:
            print('  · %s→%s 已移或無此段' % (src, dst))
            continue
        rest = [l for l in lines if l not in hit]
        plain[src] = '\n'.join(rest)
        plain[dst] = '\n'.join(hit + ([plain[dst]] if plain.get(dst) else []))
        print('白話 %s→%s：%s' % (src, dst, why))
    for k, subs in PLAIN_FIX.items():
        v = plain.get(k, '')
        for old, new, why in subs:
            if old not in v:
                print('  ✗ %s 未命中：%s' % (k, old[:20]))
                continue
            v = v.replace(old, new, 1)
            print('白話 %s：%s' % (k, why))
        plain[k] = v
    json.dump(plain, open(PLAIN, 'w', encoding='utf-8'), ensure_ascii=False, indent=0)
    print('已寫 %s' % PLAIN)


if __name__ == '__main__':
    main()
