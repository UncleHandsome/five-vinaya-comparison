issues = []
for f in sorted(glob.glob(os.path.join(W, 'findings', 'vol*.md'))):
    name = os.path.basename(f)
    m = re.match(r'vol(\d+)', name)
    if not m:
        continue
    v = int(m.group(1))
    text = open(f, encoding='utf-8').read()
    src = vols[v]
    # extract quote lines
    lines = text.split('\n')
    in_quote = False
    buf = []
    quotes = []
    for ln in lines:
        s = ln.strip()
        if s.startswith('>'):
            buf.append(s.lstrip('>').strip())
            in_quote = True
        else:
            if in_quote and buf:
                quotes.append(''.join(buf))
                buf = []
            in_quote = False
    if buf:
        quotes.append(''.join(buf))
    bad = []
    for q in quotes:
        if '底本：' in q or '`_work/' in q:
            continue  # 卷首說明，非引文
        # strip in-line segment markers such as （段4）、〔段12〕、**段4**、（節引）
        for _ in range(3):
            q = re.sub(r'[（(〔]\s*段\s*\d+[^）)〕]{0,24}[）)〕]', '', q)
            q = re.sub(r'\*\*\s*段\s*\d+[^*]{0,12}\*\*', '', q)
            q = re.sub(r'[（(]\s*(?:節引|節錄|後段|中段|前段|末句|僅引[^）)]{0,12})[）)]', '', q)
            q = re.sub(r'段\s*\d+\s*(?:[～~\-–]\s*\d+\s*)?[：:]', '', q)
        segs = re.split(r'（中略[^）]*）|……|\.\.\.', q)
        for seg in segs:
            n = norm(seg)
            if len(n) < 6:
                continue
            if n not in src:
                bad.append(seg[:40])
    # simplified check
    bad_simp = sorted(set(c for c in text if c in simp))
    print('%s: quotes=%d bad=%d simp=%s' % (name, len(quotes), len(bad), ''.join(bad_simp) if bad_simp else '-'))
    for b in bad[:5]:
        print('    NOT FOUND:', b)
