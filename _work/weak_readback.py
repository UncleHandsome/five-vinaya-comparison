# 緩存已讀文件
_file_cache = {}

def read_law_file(law, vol):
    """讀取對律原文文件"""
    vol_key = f"卷{vol}"
    if law not in LAW_FILES or vol_key not in LAW_FILES[law]:
        return None
    filepath = os.path.join(LAW_ROOT, LAW_FILES[law][vol_key])
    if filepath in _file_cache:
        return _file_cache[filepath]
    try:
        with open(filepath, "r", encoding="utf-8") as f:
            text = f.read()
        _file_cache[filepath] = text
        return text
    except:
        return None

def find_volumes_in_text(law, vol):
    """在文件中定位卷的起止"""
    text = read_law_file(law, vol)
    if not text:
        return None, None
    # 搜索卷標
    # 十誦: "十誦律卷第二十一"  僧祇: "摩訶僧祇律卷第一"  根有: "根本說一切有部毘奈耶卷第一"  五分: "彌沙塞五分律卷第一"
    patterns = {
        "十誦": rf"十誦律卷第{['一','二','三','四','五','六','七','八','九','十'][int(vol)-1] if int(vol)<=10 else ''}"
                   if int(vol) <= 10 else rf"十誦律卷第{vol}",
        "僧祇": rf"摩訶僧祇律卷第{['一','二','三','四','五','六','七','八','九','十'][int(vol)-1] if int(vol)<=10 else ''}"
                   if int(vol) <= 10 else rf"摩訶僧祇律卷第{vol}",
        "根有": rf"根本說一切有部毘奈耶卷第{['一','二','三','四','五','六','七','八','九','十'][int(vol)-1] if int(vol)<=10 else ''}"
                   if int(vol) <= 10 else rf"根本說一切有部毘奈耶卷第{vol}",
        "五分": rf"彌沙塞五分律卷第{['一','二','三','四','五','六','七','八','九','十'][int(vol)-1] if int(vol)<=10 else ''}"
                   if int(vol) <= 10 else rf"彌沙塞五分律卷第{vol}",
    }
    # 簡化：直接搜索卷數
    return text

def search_context(law, vol, query, context_chars=300):
    """在對律的指定卷中搜索命中字串，返回上下文"""
    text = read_law_file(law, vol)
    if not text:
        return f"[文件未找到: {law} 卷{vol}]"
    
    idx = text.find(query)
    if idx == -1:
        # 嘗試在整個文件中搜索（可能跨卷）
        return f"[字串'{query}'在{law}卷{vol}未找到]"
    
    start = max(0, idx - context_chars)
    end = min(len(text), idx + len(query) + context_chars)
    context = text[start:end]
    return context

# 解析弱候選清單
def parse_weak_candidates():
    """從 collide_report.md 解析第二節的169項弱候選"""
    with open(os.path.join(WORK, "collide_report.md"), "r", encoding="utf-8") as f:
        lines = f.readlines()
    
    candidates = []
    in_section2 = False
    for i, line in enumerate(lines):
        if "## 二、弱候選" in line:
            in_section2 = True
            continue
        if in_section2 and line.startswith("## ") and "弱候選" not in line:
            break
        if not in_section2:
            continue
        # 解析表格行
        # | # | 主稿 | 項 | 題 | 對律 | 卷段 | 命中字串 |
        m = re.match(r'\|\s*(\d+)\s*\|\s*(\S+)\s*\|\s*(\S+)\s*\|\s*(.+?)\s*\|\s*(\S+)\s*\|\s*(.+?)\s*\|\s*(.+?)\s*\|', line)
        if m:
            candidates.append({
                "num": int(m.group(1)),
                "source": m.group(2),
                "item": m.group(3),
                "title": m.group(4).strip(),
                "target": m.group(5).strip(),
                "location": m.group(6).strip(),
                "query": m.group(7).strip(),
            })
    return candidates

# 主程序
candidates = parse_weak_candidates()
print(f"解析到 {len(candidates)} 項弱候選")

# 逐項搜索上下文
results = []
for c in candidates:
    law = c["target"]
    loc = c["location"]  # e.g. "卷27段31"
    
    # 提取卷號
    vol_match = re.search(r'卷(\d+)', loc)
    vol = vol_match.group(1) if vol_match else None
    
    if not vol:
        results.append({**c, "context": f"[無法解析卷號: {loc}]", "verdict": "存疑"})
        continue
    
    # 提取段號（用於參考，但原文無段號標記）
    seg_match = re.search(r'段(\d+)', loc)
    seg = seg_match.group(1) if seg_match else "?"
    
    # 搜索命中字串
    query = c["query"]
    context = search_context(law, vol, query, 400)
    
    results.append({**c, "vol": vol, "seg": seg, "context": context})

# 輸出結果
output_path = os.path.join(WORK, "weak_verdicts.json")
with open(output_path, "w", encoding="utf-8") as f:
    json.dump(results, f, ensure_ascii=False, indent=2)

# 也輸出為可讀的 markdown
md_path = os.path.join(WORK, "weak_verdicts.md")
with open(md_path, "w", encoding="utf-8") as f:
    f.write("# 弱候選逐條回讀（上下文抽取）\n\n")
    f.write("> 本表為169項弱候選的對律原文上下文抽取結果，供逐條裁定。\n\n")
    for r in results:
        f.write(f"## 弱#{r['num']}　{r['source']} {r['item']}\n\n")
        f.write(f"- **題**：{r['title']}\n")
        f.write(f"- **對律**：{r['target']} {r['location']}\n")
        f.write(f"- **命中字串**：{r['query']}\n\n")
        f.write(f"### 對律上下文\n\n")
        f.write(f"```\n{r.get('context', '[無]')}\n```\n\n")
        f.write(f"---\n\n")

print(f"結果已寫入 {output_path} 和 {md_path}")
print(f"共處理 {len(results)} 項")
