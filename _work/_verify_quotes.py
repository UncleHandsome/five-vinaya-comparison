def load(v):
    d = {}
    for line in open(v, encoding='utf-8').read().split('\n'):
        line = line.rstrip('\r')
        if not line.strip():
            continue
        parts = line.split('\t', 1)
        if len(parts) == 2:
            try:
                d[int(parts[0])] = parts[1]
            except Exception:
                pass
    return d

