def norm(s):
    s = re.sub(r'[\s\u3000]', '', s)
    return re.sub(r'[^\u4e00-\u9fff]', '', s)

def vol_text(v):
    p = os.path.join(W, 'wufen', 'vol%02d.txt' % v)
    return ''.join(t for _, t in (l.rstrip('\n').split('\t', 1) for l in open(p, encoding='utf-8')))

def clean_quote_line(s):
    s = s.strip()
    if not s.startswith('>'):
        return s
    body = s.lstrip('>').strip()
    if body.startswith(('底本：', '對校本：', '凡例')):
        return None
    m = re.match(r'^段\s*(\d+)\s*[（(]節錄[）)]\s*[：:]\s*(.*)$', body)
    if m:
        return '> **段%s（節錄）**　%s' % (m.group(1), m.group(2))
    m = re.match(r'^段\s*(\d+)\s*[：:]\s*(.*)$', body)
    if m:
        return '> **段%s**　%s' % (m.group(1), m.group(2))
    m = re.match(r'^〔段([^〕]{1,12})〕\s*(.*)$', body)
    if m:
        return '> **段%s**　%s' % (m.group(1), m.group(2))
    m = re.match(r'^（段([^）]{1,12})）\s*(.*)$', body)
    if m:
        return '> **段%s**　%s' % (m.group(1), m.group(2))
    return '> ' + body if body else '>'

def clean_item(title, body):
    out = [title, '']
    for raw in body.split('\n'):
        s = raw.strip()
        if s.startswith('>'):
            c = clean_quote_line(s)
            if c is None:
                continue
            c = re.sub(r'(段\s*\d+\s*[–\-]\s*\d+\s*[：:])', r'\n>\n> **\1**　', c)
            c = re.sub(r'(段\s*\d+\s*[：:])', r'\n>\n> **\1**　', c)
            out.extend(c.split('\n'))
        else:
            out.append(raw.rstrip())
    t = '\n'.join(out)
    t = re.sub(r'^\s*-\s*', '- ', t, flags=re.M)
    t = re.sub(r'\n{3,}', '\n\n', t)
    return t.strip()

