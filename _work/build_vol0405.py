import os

BASE = '<PROJ>/_work'

def load(v):
    d = {}
    for line in open(os.path.join(BASE, v), encoding='utf-8').read().split('\n'):
        line = line.rstrip('\r')
        if not line.strip():
            continue
        p = line.split('\t', 1)
        if len(p) == 2:
            try:
                d[int(p[0])] = p[1]
            except Exception:
                pass
    return d

