# -*- coding: utf-8 -*-
import re, io
p='findings_mk/vol12-13.md'
s=io.open(p,encoding='utf-8').read()
cut=s.index('## 敘事抽取')
head, tail = s[:cut], s[cut:]

def bump(m):
    n=int(m.group(1))
    if 12<=n<=26:
        return '### %d. '%(n+1)
    return m.group(0)
head = re.sub(r'^### (\d+)\. ', bump, head, flags=re.M)

new = u"""### 12. 更發起波夜提之行為主體擴為六類比丘，別立「見不欲」一格
- 位置：卷12·段43
- 四分律對照：sifen/019_九十單提法之七.txt 段31：「彼比丘知諍事如法滅已，後更發起作如是言：『不善觀不成觀，不善解不成解，不善滅不成滅。』說而了了者，波逸提。」未列行為主體之種類。
- 五分律對照：wufen/vol06.txt 段63：「若僧如法斷事而發起者，波逸提；若僧不羯磨斷事，而發起者，突吉羅；若發起私事，突吉羅。」未列行為主體之種類。
- 十誦律對照：shisong/vol09.txt 段90：「還更發起者，作如是言：『諸長老！是事非作惡作，應更作；非斷惡斷，更斷；非停惡停，更停；非滅惡滅，更滅。』」未列行為主體之種類。
- 差異說明：三律於此戒只作「若僧如法斷事而發起者，波逸提」之概括表述，不問發起者身分。本律則將得波夜提之行為主體明列為六類在會之比丘——客比丘、去比丘、與欲比丘、見不欲比丘、新受戒比丘、在坐睡比丘，並規定其所說之內容為「不好羯磨、別佛別法別僧、如牛羊僧、羯磨不成就」。其中「見不欲」（身在僧中而心不欲）為三律絕無之範疇，等於把「未參與者之異議」也一併入罪。
- 原文：
  > 〔卷12·段43〕若有客比丘、若去比丘、若與欲比丘、若見不欲比丘、若新受戒比丘、若在坐睡比丘，是諸比丘作是言：『如是不好羯磨，別佛、別法、別僧，如牛羊僧，不善羯磨，羯磨不成就。』阿難！如是更發起者，得波夜提罪，是名相言諍。
- 白話：
  若有客比丘、有離去的比丘、有與欲的比丘、有身在眾中而心不欲的比丘、有新受戒的比丘、有在座中睡眠的比丘，這些比丘這樣說：「這樣的羯磨不好，是別於佛、別於法、別於僧，像牛羊一樣的僧，是不善的羯磨，羯磨不成就。」阿難！像這樣再發起的人，得波夜提罪，這就叫相言諍。

"""
marker = u'### 13. 比丘僧如法喚比丘尼僧不來者得越毘尼'
assert marker in head
head = head.replace(marker, new + marker, 1)
tail = tail.replace(u'保留項 13', u'保留項 14').replace(u'保留項 12', u'保留項 13')
io.open(p,'w',encoding='utf-8').write(head+tail)
print('ok')
