def apply(r):
    """就地覆蓋渲染用欄位，回傳新 dict（不改原物件）"""
    e = ERRATA.get(r['id'])
    if not e:
        return r
    r = dict(r)
    for k, v in e.items():
        if k.startswith('_'):
            continue
        if k == 'cells':
            for ck, cv in v.items():
                r[ck] = cv
            continue
        r[k] = v
    # 局部字串替換：_sub = [(欄位, 原文, 新文), ...]
    for spec in e.get('_sub', []):
        fld, old, new = spec
        if r.get(fld) and old in r[fld]:
            r[fld] = r[fld].replace(old, new, 1)
    return r


import re as _re

_CN_D = {'一': 1, '二': 2, '三': 3, '四': 4, '五': 5,
         '六': 6, '七': 7, '八': 8, '九': 9}


def cn2num(s):
    """中文數字轉阿拉伯數字，支援「二十四」「一百七十八」等複合式。"""
    s = (s or '').strip()
    if not s:
        return 0
    if s == '十':
        return 10
    if '百' in s:
        a, _, b = s.partition('百')
        n = (_CN_D.get(a, 1) if a else 1) * 100
        if not b:
            return n
        if b == '十':
            return n + 10
        if '十' in b:
            c, _, d = b.partition('十')
            return n + (_CN_D.get(c, 1) if c else 1) * 10 + _CN_D.get(d, 0)
        return n + _CN_D.get(b, 0)
    if '十' in s:
        a, _, b = s.partition('十')
        return (_CN_D.get(a, 1) if a else 1) * 10 + _CN_D.get(b, 0)
    return _CN_D.get(s, 0)


