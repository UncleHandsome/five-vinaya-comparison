def clean_title(t, rid=None):
    """去除標題中的段號後綴與分類標籤，並統一戒號為四分律。"""
    t = (t or '').strip()
    if rid and rid in JIE_NO_FIX:
        old, new = JIE_NO_FIX[rid]
        if t.startswith(old):
            t = new + t[len(old):]
    t = RE_TITLE_SEG.sub('', t).strip()
    for tag in TITLE_TAGS:
        t = t.replace(f'（{tag}）', '')
    # 根有稿初編時把層級寫在標題末尾，與 lv 欄重複，去之
    t = _re.sub(r'（(?:戒條|制度|法數|事件)）\s*$', '', t)
    # 標題中的「兩律」「三律」「本律」亦還原為具體律名，與差異說明一致
    if rid:
        _r = _row_by_id(rid)
        if _r:
            from diff_fmt import expand_refs
            t = expand_refs(t, _r)
    return t.strip()


def dedup_xref(x):
    """補證欄常有「……（同樣內容）」的重複，去其重複括號（可多處）"""
    import re
    if not x:
        return x
    out = x
    for _ in range(6):
        changed = False
        for m in re.finditer(r'（([^（）]{12,})）', out):
            if m.group(1)[:20] in out[:m.start()]:
                out = out[:m.start()] + out[m.end():]
                changed = True
                break
        if not changed:
            break
    return re.sub(r'\s+', ' ', out).strip()


