def apply(r):
    """就地覆蓋渲染用欄位，回傳新 dict（不改原物件）"""
    e = ERRATA.get(r['id'])
    if not e:
        return r
    r = dict(r)
    if '_fayi' in e:
        r['_fayi'] = e['_fayi']
    for k, v in e.items():
        if k.startswith('_'):
            continue
        if k == 'cells':
            for ck, cv in v.items():
                r[ck] = cv
            continue
        r[k] = v
    # 局部字串替換：_sub = [(欄位, 原文, 新文), ...]
    for spec in e.get('_sub', []):
        fld, old, new = spec
        if r.get(fld) and old in r[fld]:
            r[fld] = r[fld].replace(old, new, 1)
    # 末尾追加：_append = [(欄位, 文字), ...]
    for fld, txt in e.get('_append', []):
        if r.get(fld):
            r[fld] = r[fld].rstrip() + txt
    return r


