def split_title(t, rid=None, limit=16):
    """拆為（主標題, 副標題）。有 TITLE_MAIN 者從之，否則取頂層冒號前段。"""
    t = (t or '').strip()
    m = TITLE_MAIN.get(rid or '')
    if m:
        if t.startswith(m):
            return m, t[len(m):].lstrip('：:，,、　 ')
        return m, t
    # 自動：頂層冒號，前段 3–limit 字者
    d, marks = 0, []
    for i, ch in enumerate(t):
        if ch in '（「『〈《【':
            d += 1
        elif ch in '）」』〉》】':
            d = max(0, d - 1)
        elif d == 0 and ch in '：:，；':
            marks.append((i, ch))
    for i, ch in marks:
        if ch in '：:' and 3 <= i <= limit:
            return t[:i], t[i + 1:]
    # 次：無冒號而逾 23 字者，取最後一個頂層逗號／分號為斷（前段 6–limit 字）
    if len(t) >= 24:
        cand = [i for i, ch in marks if ch in '，；' and 6 <= i <= limit]
        if cand:
            i = max(cand)
            return t[:i], t[i + 1:]
    return t, ''


def clean_title(t, rid=None):
    """去除標題中的段號後綴與分類標籤，並統一戒號為四分律。"""
    t = (t or '').strip()
    if rid and rid in JIE_NO_FIX:
        old, new = JIE_NO_FIX[rid]
        if t.startswith(old):
            t = new + t[len(old):]
    t = RE_TITLE_SEG.sub('', t).strip()
    for tag in TITLE_TAGS:
        t = t.replace(f'（{tag}）', '')
    # 根有稿初編時把層級寫在標題末尾，與 lv 欄重複，去之
    t = _re.sub(r'（(?:戒條|制度|法數|事件)）\s*$', '', t)
    # 標題中的「兩律」「三律」「本律」亦還原為具體律名，與差異說明一致
    if rid:
        _r = _row_by_id(rid)
        if _r:
            from diff_fmt import expand_refs
            t = expand_refs(t, _r)
    return t.strip()


def dedup_xref(x):
    """補證欄常有「……（同樣內容）」的重複，去其重複括號（可多處）"""
    import re
    if not x:
        return x
    out = x
    for _ in range(6):
        changed = False
        for m in re.finditer(r'（([^（）]{12,})）', out):
            if m.group(1)[:20] in out[:m.start()]:
                out = out[:m.start()] + out[m.end():]
                changed = True
                break
        if not changed:
            break
    return re.sub(r'\s+', ' ', out).strip()


