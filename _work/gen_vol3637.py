import io, os

BASE = os.path.dirname(os.path.abspath(__file__))

def seg(v, n):
    for ln in io.open(os.path.join(BASE, 'shisong', 'vol%d.txt' % v), encoding='utf-8'):
        p = ln.rstrip('\n').split('\t')
        if len(p) >= 2 and p[0].strip() == str(n):
            return p[1]
    raise KeyError((v, n))

def cut(v, n, a, b):
    s = seg(v, n)
    i = s.find(a)
    j = s.find(b, i)
    assert i >= 0 and j >= 0, (v, n, a, b, i, j)
    return s[i:j + len(b)]

