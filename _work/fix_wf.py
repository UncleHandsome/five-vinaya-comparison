cnt = {'t1_merge': 0, 't1_bare': 0, 'gloss': {}, 'row': {}}
for f in BOOKS:
    p = os.path.join(D, f)
    md = io.open(p, encoding='utf-8').read()
    md2, mg, br = t1(md)
    cnt['t1_merge'] += mg
    cnt['t1_bare'] += br
    for gi, (old, new) in enumerate(GLOSS):
        n = md2.count(old)
        if n:
            md2 = md2.replace(old, new)
            cnt['gloss'][gi] = cnt['gloss'].get(gi, 0) + n
    for ri, (old, new) in enumerate(ROWS):
        n = md2.count(old)
        if n:
            md2 = md2.replace(old, new)
            cnt['row'][ri] = cnt['row'].get(ri, 0) + n
    if md2 != md and not DRY:
        io.open(p, 'w', encoding='utf-8').write(md2)

