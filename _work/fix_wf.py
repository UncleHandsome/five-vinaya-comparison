def t1(md):
    """只刪裸 '>' 空引言行。全書『  **段N**』獨標之式為既有自制（750 處），
    非本病所在，故不動——藥須對容器粒度。"""
    L = md.split('\n')
    out, bare = [], 0
    for l in L:
        if l.strip() == '>':
            bare += 1
            continue
        out.append(l)
    return '\n'.join(out), 0, bare


