def seg(src, pid, start, end):
    t = src[pid]
    i = t.find(start)
    assert i >= 0, ('start', pid, start[:20])
    j = t.find(end, i)
    assert j >= 0, ('end', pid, end[:20])
    return t[i:j + len(end)]


def cq(src, pid, start, end):
    return '「' + seg(src, pid, start, end) + '」'


