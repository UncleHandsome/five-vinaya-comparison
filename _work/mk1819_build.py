BASE = os.path.dirname(os.path.abspath(__file__))

def load(vol):
    d = {}
    p = os.path.join(BASE, 'sengqi', 'vol%s.txt' % vol)
    for line in io.open(p, encoding='utf-8'):
        m = re.match(r'^(\d+)\t(.*)$', line.rstrip('\n'))
        if m:
            d[m.group(1)] = m.group(2)
    return d

SRC = {'18': load('18'), '19': load('19')}
TOTAL = sum(len(v) for v in SRC['18'].values()) + sum(len(v) for v in SRC['19'].values())

def extract(vol, seg, start, end):
    s = SRC[vol][seg]
    i = 0 if start is None else s.index(start)
    if end is None:
        j = len(s)
    else:
        j = s.index(end, i) + len(end)
    return s[i:j]

