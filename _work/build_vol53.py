def parse_ranges(s):
    out = []
    for m in re.finditer(r'53-(\d+)(?:～(?:53-)?(\d+))?', s):
        a = int(m.group(1)); b = int(m.group(2) or a)
        out.extend(range(a, b + 1))
    return out

