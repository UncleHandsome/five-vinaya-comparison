def load(v):
    d = {}
    for line in io.open(os.path.join(BASE, 'shisong', 'vol%s.txt' % v), encoding='utf-8').read().splitlines():
        p = line.split('\t')
        if len(p) >= 2 and p[0].isdigit():
            d[int(p[0])] = p[1]
    return d

