def extract(seg, s, e):
    src = segs[seg]
    i = src.find(s)
    j = src.find(e, i)
    if i < 0 or j < 0:
        raise SystemExit('anchor fail %s %s | %s' % (seg, s[:20], e[:20]))
    return src[i:j + len(e)]

blocks = {}
for k, qs in Q.items():
    out = []
    for seg, s, e in qs:
        out.append('  > %d：%s' % (seg, extract(seg, s, e)))
    blocks[k] = out

text = open(mdp, encoding='utf-8').read().split('\n')
res = []
i = 0
cur = None
while i < len(text):
    ln = text[i]
    m = re.match(r'### (\d+)\. ', ln)
    if m:
        cur = int(m.group(1))
    if ln.strip() == '- 原文：' and cur in blocks:
        res.append(ln)
        res.extend(blocks[cur])
        i += 1
        while i < len(text) and text[i].startswith('  > '):
            i += 1
        continue
    res.append(ln)
    i += 1
open(mdp, 'w', encoding='utf-8').write('\n'.join(res))
print('rewrote quotes for', len(blocks), 'items')
