def load_sifen(fn):
    d = {}
    for L in open(f'_work/sifen/{fn}.txt', encoding='utf-8').read().split('\n'):
        if not L.strip():
            continue
        n, t = L.split('\t', 1)
        d[int(n)] = t
    return d

def load_wufen():
    d = {}
    for L in open('_work/bundles/W05.txt', encoding='utf-8').read().split('\n'):
        if not L.strip():
            continue
        parts = L.split('\t')
        d[parts[0]] = '\t'.join(parts[1:])
    return d

