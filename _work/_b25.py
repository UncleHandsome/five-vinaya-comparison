import io, re, os, json

BASE = os.path.dirname(os.path.abspath(__file__))

def load(path):
    d = {}
    for line in io.open(os.path.join(BASE, path), encoding='utf-8'):
        if '\t' in line:
            n, x = line.rstrip('\n').split('\t', 1)
            d[int(n)] = x
    return d

V25 = load('sengqi/vol25.txt')
V26 = load('sengqi/vol26.txt')
SF = {}
for f in os.listdir(os.path.join(BASE, 'sifen')):
    if f.endswith('.txt'):
        for k, v in load('sifen/' + f).items():
            SF[(f[:3], k)] = v
WF = {}
for i in range(1, 31):
    f = 'vol%02d.txt' % i
    for k, v in load('wufen/' + f).items():
        WF[(i, k)] = v
SS = {}
for i in range(1, 62):
    f = 'vol%02d.txt' % i
    for k, v in load('shisong/' + f).items():
        SS[(i, k)] = v

def take(s, start=None, end=None, n=None):
    i = 0 if start is None else s.index(start)
    if end is not None:
        j = s.index(end, i) + len(end)
    elif n is not None:
        j = i + n
    else:
        j = len(s)
    return s[i:j]

def q(src, vol, n, start=None, end=None, ln=None):
    s = (V25 if vol == 25 else V26)[n] if src == 'mk' else (
        SF[(vol, n)] if src == 'sf' else (WF[(vol, n)] if src == 'wf' else SS[(vol, n)]))
    return take(s, start, end, ln)

