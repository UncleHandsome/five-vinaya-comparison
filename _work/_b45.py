# -*- coding: utf-8 -*-
import os, re

BASE = '<PROJ>/_work'

def load(fn):
    d = {}
    for line in open(os.path.join(BASE, fn), encoding='utf-8').read().split('\n'):
        line = line.replace('\r', '')
        if not line.strip():
            continue
        p = line.split('\t', 1)
        if len(p) == 2:
            d[int(p[0])] = p[1]
    return d

V4 = load('genben/vol04.txt')
V5 = load('genben/vol05.txt')
SRC = {'4': V4, '5': V5}

QUOTES = []

def grab(vol, seg, a, b):
    t = SRC[vol][seg]
    i = t.find(a)
    assert i >= 0, ('起錨未見 vol%s 段%s: %r' % (vol, seg, a))
    j = t.find(b, i)
    assert j >= 0, ('迄錨未見 vol%s 段%s: %r' % (vol, seg, b))
    return t[i:j + len(b)]

def Qg(vol, seg, a, b):
    t = (vol, seg, grab(vol, seg, a, b))
    QUOTES.append(t)
    return t

def Q(vol, seg):
    t = (vol, seg, SRC[vol][seg])
    QUOTES.append(t)
    return t

def wrap(vol, seg, text, width=92):
    parts = re.split(r'(?<=[。！？])', text)
    parts = [p for p in parts if p]
    lines, cur = [], ''
    for p in parts:
        if cur and len(cur) + len(p) > width:
            lines.append(cur)
            cur = p
        else:
            cur += p
    if cur:
        lines.append(cur)
    return '\n'.join('  > 〔卷%s·段%d〕%s' % (vol, seg, ln) for ln in lines)

