# -*- coding: utf-8 -*-
import re
def load(v):
    d={}
    for line in open('sengqi/vol%d.txt'%v,encoding='utf-8'):
        m=re.match(r'^(\d+)\t(.*)$',line.rstrip('\n'))
        if m: d[int(m.group(1))]=m.group(2)
    return d
S={20:load(20),21:load(21)}
txt=open('findings_mk/vol20-21.md',encoding='utf-8').read()
bad=[]; n=0; chars=0
for ln in txt.split('\n'):
    m=re.match(r'^> 〔卷(\d+)·段(\d+)〕(.*)$',ln)
    if not m: 
        if ln.startswith('>'): bad.append(('NO_TAG',ln[:60]))
        continue
    v=int(m.group(1)); p=int(m.group(2)); body=m.group(3)
    n+=1; chars+=len(re.sub(r'\s','',body))
    if body not in S[v][p]:
        bad.append((v,p,body[:80]))
print('quotes',n,'chars',chars)
print('bad',len(bad))
for b in bad[:10]: print(b)
